const LOGO_GRADIENT = [0, 0, 1, 1, 2, 2] as const
const CADUC_GRADIENT = [2, 2, 1, 1, 0, 0, 1, 1, 2, 2, 3, 3, 3, 3, 3] as const

const colorize = (art: string[], gradient: readonly number[], c: ThemeColors): ArtLine[] => {
  const p = [c.primary, c.accent, c.border, c.muted]

  return art.map((text, i) => [[p[gradient[i]!] ?? c.muted, text]])
}

export const LOGO_WIDTH = 98
export const CADUCEUS_WIDTH = 30

export const logo = (c: ThemeColors, customLogo?: string): ArtLine[] =>
  customLogo ? parseRichMarkup(customLogo) : colorize(LOGO_ART, LOGO_GRADIENT, c)

export const caduceus = (c: ThemeColors, customHero?: string): ArtLine[] =>
  customHero ? parseRichMarkup(customHero) : colorize(CADUCEUS_ART, CADUC_GRADIENT, c)

export const artWidth = (lines: ArtLine[]) =>
  lines.reduce((m, line) => Math.max(m, line.reduce((sum, [, text]) => sum + stringWidth(text), 0)), 0)

export type ArtLine = ArtSegment[]
export type ArtSegment = [string, string]
